await T.wait(500);
T.button('Add').click();
for (let i = 0; i < 20 && !T.q('.p-dialog, [role=dialog]'); i++) await T.wait(200);
await T.wait(600);
const dlg = T.q('.p-dialog, [role=dialog]');
const sels = () => T.qa('app-select-field p-select', dlg);
const out = {};
out.channels = await T.options(sels()[0]);
await T.pick(sels()[0], out.channels.find((o) => /Agent Online/i.test(o)));
out.productTypes = await T.options(sels()[1]);
await T.pick(sels()[1], out.productTypes.find((o) => /อุบัติเหตุ|Accident/i.test(o)) ?? out.productTypes[0]);
out.subTypes = await T.options(sels()[2]);
await T.pick(sels()[2], null);
out.packages = await T.options(sels()[3]);
const pk = out.packages.find((o) => /ST000030/.test(o));
if (pk) await T.pick(sels()[3], pk);
out.values = T.qa('app-select-field .p-select-label', dlg).map((e) => T.norm(e.textContent));
out.card = T.norm(T.q('.pkg-card, .package-card, .card', dlg)?.textContent);
return out;
